#!/usr/bin/env python3
"""Generate the item / gacha data files from research/spec.

Outputs (BigStoryIdleRPG/Data/):
  Summon.lua      weapon summon + companion summon levels, rates (integer weights), pity rows
  Weapons.lua     29 weapon tiers: per-level equip/owned ATK% (raw 0.1 %), hit, attack speed, enhance cost
  Companions.lua  69 companions, per-level stat curves (raw units, deduplicated), level-up constants,
                  main-companion attack inheritance (link), slot unlocks, skill texts
  Equipment.lua   15 parts, 291 gear records, option pools, level factors (Lv1-140), sub-line odds,
                  sub-option conversion costs, elite monster summoning (40 KR levels), drop tables

Inputs:
  research/spec/items-gacha.json            (KR client 1.18.0 via mapleidleindex)
  research-progression.json                 (KR elite summon table + companion constants via mekipick)
      searched at research/spec/research-progression.json, or --progression PATH, or $BSIR_PROGRESSION

Usage (from the repository root):  python3 -I tools/gen_items.py [--progression PATH]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from luagen import to_lua  # noqa: E402

ROOT = os.path.dirname(HERE)
SPEC = os.path.join(ROOT, "research", "spec")
OUT = os.path.join(ROOT, "BigStoryIdleRPG", "Data")

MAX_ITEM_LEVEL = 140          # max character level (combat-stages leveling.maxCharacterLevel)

HEADER = ("-- GENERATED by tools/gen_items.py from research/spec. Do not edit by hand.\n"
          "local ADDON, ns = ...\nns.Data = ns.Data or {}\nlocal D = ns.Data\n")


def write(path, assignments, note=None):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        if note:
            for line in note.strip().splitlines():
                f.write("-- " + line + "\n")
        for lhs, value, indent in assignments:
            f.write("%s = %s\n" % (lhs, to_lua(value, indent, 0)))
    print("wrote", os.path.relpath(path, ROOT), os.path.getsize(path), "bytes")


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def find_progression(argv):
    cands = []
    if "--progression" in argv:
        cands.append(argv[argv.index("--progression") + 1])
    if os.environ.get("BSIR_PROGRESSION"):
        cands.append(os.environ["BSIR_PROGRESSION"])
    cands.append(os.path.join(SPEC, "research-progression.json"))
    for c in cands:
        if c and os.path.exists(c):
            return load_json(c)
    raise SystemExit("research-progression.json not found (put it in research/spec or pass --progression PATH)")


def raw(v, div):
    """display value -> client raw integer (percent stats are stored x10)."""
    r = round(v * div)
    assert abs(r - v * div) < 1e-6, (v, div)
    return int(r)


def pct_weight(p, scale):
    w = round(p * scale)
    assert abs(w - p * scale) < 1e-6, (p, scale)
    return int(w)


# ---------------------------------------------------------------------------
# Summon (weapon + companion)
# ---------------------------------------------------------------------------
WEAPON_WEIGHT_SCALE = 100000      # percent * 1e5 -> per 10,000,000 (same unit as the client reward table)
COMPANION_WEIGHT_SCALE = 1000     # percent * 1e3 -> per 100,000 (same unit as the client table)


def gen_summon(d, job_by_en):
    ws = d["weaponSummon"]
    rates = {}
    for row in ws["ratesPercentByLevel"]:
        lst = []
        for g, t, p in row["gradeTierPercent"]:
            if p > 0:
                lst.append([g, t, pct_weight(p, WEAPON_WEIGHT_SCALE)])
        total = sum(x[2] for x in lst)
        assert total == 100 * WEAPON_WEIGHT_SCALE, (row["level"], total)
        rates[row["level"]] = lst
    weapon = {
        "maxLevel": ws["maxLevel"],
        "levelUp": [s["requiredCount"] for s in ws["levelUp"]["steps"]],   # [L] = pulls for L -> L+1
        "cost": {"ticket": ws["costPerPull"][0]["count"], "redDia": ws["costPerPull"][1]["count"]},
        "maxDraw": [ws["maxDrawCountPerLevel"][str(i)] for i in range(1, ws["maxLevel"] + 1)],
        "totalWeight": 100 * WEAPON_WEIGHT_SCALE,
        "rates": rates,
        "guarantees": [{"level": g["level"], "grade": g["grade"], "tier": g["tier"], "count": g["count"]}
                       for g in ws["guarantees"]],
    }
    assert weapon["levelUp"] and len(weapon["levelUp"]) == ws["maxLevel"] - 1

    cs = d["companionSummon"]
    gw = {}
    for row in cs["gradePercentByLevel"]:
        lst = [pct_weight(row["gradePercent"][str(g)], COMPANION_WEIGHT_SCALE) for g in range(1, 6)]
        assert sum(lst) == 100 * COMPANION_WEIGHT_SCALE, (row["level"], lst)
        gw[row["level"]] = lst
    pk = cs["pickup"]
    new_names = ["플레임위자드", "소울마스터"]
    assert all(n in pk["note"] for n in new_names)
    companion = {
        "maxLevel": cs["maxLevel"],
        "levelUp": [s["requiredCount"] for s in cs["levelUp"]["steps"]],
        "cost": {"ticket": cs["costPerPull"][0]["count"], "redDia": cs["costPerPull"][1]["count"]},
        "batchSizes": cs["batchSizes"],
        "totalWeight": 100 * COMPANION_WEIGHT_SCALE,
        "gradeWeights": gw,
        "guarantees": [{"level": g["level"], "grade": g["grade"], "count": g["count"]} for g in cs["guarantees"]],
        # 1.18.0 pickup banner: a legendary result is 30 % / 30 % for the two new companions,
        # 40 % shared by the other 14 (companion.html legendaryShareRows).
        "pickup": {
            "targets": ["flameWizard", "soulMaster"],
            "newSharePermille": 300,
            "otherSharePermille": 400,
            "legendaryShareRows": pk["legendaryShareRows"],
        },
    }
    labels = {
        "grades": {g["grade"]: g["ko"] for g in ws["grades"]},
        "tiers": {t["tier"]: t["ko"] for t in ws["tiers"]},
        "companionGrades": {g["grade"]: g["ko"] for g in cs["gradePools"]},
    }
    write(os.path.join(OUT, "Summon.lua"), [
        ("D.SummonLabels", labels, " "),
        ("D.WeaponSummon", weapon, None),
        ("D.CompanionSummon", companion, None),
    ], note="""
Weapon / companion summon (client 1.18.0 GachaLevelTable, WeaponLevelGachaRewardTable,
SupporterLevelGachaRewardTable, *GachaGuaranteedTable via mapleidleindex summon-levels.json,
companion-summon-rewards.json). Rates are integer weights: weapon per 10,000,000, companion grade per 100,000.
levelUp[L] = pulls needed for L -> L+1 (1 summon EXP per pull). maxDraw[L] = most pulls in one go.""")


# ---------------------------------------------------------------------------
# Weapons
# ---------------------------------------------------------------------------
def gen_weapons(d):
    w = d["weapons"]
    tiers = []
    for t in sorted(w["tiers"], key=lambda x: x["order"]):
        pl = t["perLevel_1to200"]
        hit = set(pl["accuracy"])
        aspd = set(pl["attackSpeedPercent"])
        assert len(hit) == 1 and len(aspd) == 1, t["id"]
        cost = pl["enhanceStoneCostToReach"]
        cum = pl["enhanceStoneCumulative"]
        assert cost[0] == 0 and all(sum(cost[:i + 1]) == cum[i] for i in range(len(cost))), t["id"]
        tiers.append({
            "id": t["id"],
            "grade": t["grade"],
            "tier": t["tier"],
            "label": t["labelKo"],
            "equipM": [raw(v, 10) for v in pl["equipAttackPercent"]],
            "ownedM": [raw(v, 10) for v in pl["ownedAttackPercent"]],
            "hit": hit.pop(),
            "aspdM": raw(aspd.pop(), 10),
            "cost": cost,
        })
        assert t["awakeningMaxLevel"] == {"0": 100, "1": 120, "2": 140, "3": 160, "4": 180, "5": 200}
    data = {
        "maxLevel": w["levelRange"][1],
        "awakenMaxLevel": {0: 100, 1: 120, 2: 140, 3: 160, 4: 180, 5: 200},
        "tiers": tiers,
    }
    write(os.path.join(OUT, "Weapons.lua"), [("D.Weapons", data, None)], note="""
Weapons (weapon-comparison-117.json / weapon-enhancement-costs-117.json, client 1.18.0).
29 grade x tier entries, identical for all 16 jobs. Arrays are per level 1..200:
  equipM / ownedM = equip / owned ATK% in raw 0.1 % units (display % x 10)
  hit = flat 명중 (HitChance), aspdM = attack speed raw 0.1 % (chained stat)
  cost[L] = 무기 강화석 to go from L-1 to L (cost[1] = 0).""")


# ---------------------------------------------------------------------------
# Companions
# ---------------------------------------------------------------------------
GRADE_ID = {"normal": 1, "rare": 2, "epic": 3, "unique": 4, "legendary": 5}


def gen_companions(d, prog, job_by_en):
    c = d["companions"]
    pc = prog["companions"]
    stats = c["stats"]
    job_en = {j["id"]: j["en"] for j in c["jobs"]}
    curves, curve_idx = [], {}

    def curve(arr):
        key = tuple(arr)
        if key not in curve_idx:
            curves.append(list(arr))
            curve_idx[key] = len(curves)
        return curve_idx[key]

    defs = {x["id"]: x for x in pc["companionDefs"]}
    F = pc["perLevelStatFactors"]
    comps = []
    for x in sorted(c["companions"], key=lambda y: y["supporterIndex"]):
        sid = x["supporterIndex"]
        grade = GRADE_ID[x["grade"]]
        rec = {
            "sid": sid,
            "name": x["nameKo"],
            "nameEn": x["nameEn"],
            "job": job_by_en[job_en[x["job"]]],
            "grade": grade,
            "maxLevel": x["maxLevel"],
            "equip": [],
            "owned": [],
        }
        for kind, dst in (("equipped", "equip"), ("owned", "owned")):
            for stat, arr in x[kind].items():
                div = stats[stat]["divisor"]
                vals = [raw(v, div) for v in arr]
                assert len(vals) == x["maxLevel"]
                rec[dst].append([stat, curve(vals)])
        if x.get("spawnDurationMs"):
            rec["spawnMs"] = x["spawnDurationMs"]
        # cross-check against the KR SupporterTable extract (base * factor / 1000)
        df = defs[sid]
        for kind, arr in (("equip", df["equip"]), ("owned", df["collection"])):
            for e in arr:
                mine = [int(e["base"] * F[lv][e["factor"]] // 1000) for lv in range(x["maxLevel"])]
                ci = dict(rec[kind])[e["stat"]]
                assert curves[ci - 1] == mine, (x["nameKo"], kind, e["stat"])
        comps.append(rec)
    assert len(comps) == 69

    grades = []
    gdefs = pc["grades"]
    for gi, gid in enumerate(["normal", "rare", "epic", "unique", "legendary"], start=1):
        g = gdefs["Grade%d" % gi]
        meta = [x for x in c["grades"] if x["id"] == gid][0]
        assert meta["maxLevel"] == g["maxLevel"]
        grades.append({
            "id": gid,
            "ko": meta["ko"],
            "maxLevel": g["maxLevel"],
            "beginCost": g["beginCost"],
            "costGap": g["costGap"],
            "costAdd": g["costAdd"],
            "maxCost": g["maxCost"],
            "promoteCount": g["upgradeCount"],
        })
        # formula check against the published per-level copies
        calc = [min(g["beginCost"] + (lv - 1) // g["costGap"] * g["costAdd"], g["maxCost"])
                for lv in range(1, g["maxLevel"])]
        assert calc == g["levelUpCopies"], gid

    # main companion attack inheritance (계승 공격력), per grade (identical inside a grade)
    link = {}
    for df in pc["companionDefs"]:
        gi = int(df["grade"][-1])
        lk = df["link"]
        entry = {
            "compareLevel": lk["compareLevel"],
            "m": [int(lk["base"] * F[lv][lk["factor"]] // 1000) for lv in range(df["maxLevel"])],
        }
        if gi in link:
            assert link[gi] == entry
        link[gi] = entry

    skills = {}
    for df in pc["companionDefs"]:
        s = {}
        if df.get("enter"):
            s["enter"] = df["enter"]
        acts = [{"unlock": a["unlock"], "cd": a["cooldown"], "desc": a["desc"]}
                for a in df["actives"] if not a.get("event")]
        pas = [{"unlock": a["unlock"], "trigger": a["trigger"], "chance": a["chance"], "desc": a["desc"]}
               for a in df["passives"] if not a.get("event")]
        if acts:
            s["actives"] = acts
        if pas:
            s["passives"] = pas
        if s:
            skills[df["id"]] = s

    slots = {
        "main": 1,
        "subUnlockSummonLevel": [r["gachaLevel"] for r in sorted(pc["subSlotsUnlockByCompanionSummonLevel"],
                                                                  key=lambda r: r["slot"])],
    }
    write(os.path.join(OUT, "Companions.lua"), [
        ("D.CompanionCurves", curves, None),
        ("D.CompanionGrades", grades, " "),
        ("D.Companions", comps, None),
        ("D.CompanionLink", link, None),
        ("D.CompanionSlots", slots, " "),
        ("D.CompanionSkillText", skills, None),
    ], note="""
Companions (companion-information.json, client 1.18.0) + KR SupporterTable extract (mekipick, 2026-11-15).
Curves are per level 1..maxLevel in client raw units (percent stats x10). equip/owned = {StatType, curveIndex}.
Level-up copies L->L+1 = min(beginCost + floor((L-1)/costGap)*costAdd, maxCost); promoteCount copies -> next grade.
CompanionLink[grade].m[level] = main companion attack inheritance (permille); scaled by heroLevel/compareLevel
below compareLevel. Slots: 1 main + 6 subs unlocked at companion summon level subUnlockSummonLevel[n].
CompanionSkillText: display text of the companion's battle skills (event-only passives removed).""")


