GRADE_CODE = {"Grade1": 1, "Grade2": 2, "Grade3": 3, "Grade4": 4, "Grade5": 5, "Grade5_1": 6, "Grade6": 7,
              "Grade6_1": 8}
GRADE_BY_KO = {"노말": "Grade1", "레어": "Grade2", "에픽": "Grade3", "유니크": "Grade4", "레전드리": "Grade5",
               "레전더리": "Grade5", "레전드리+": "Grade5_1", "레전더리+": "Grade5_1", "미스틱": "Grade6",
               "미스틱+": "Grade6_1"}
ELITE_GRADE = {"Normal": "Grade1", "Rare": "Grade2", "Epic": "Grade3", "Unique": "Grade4", "Legendary": "Grade5",
               "Legendary+": "Grade5_1", "Mystic": "Grade6"}
ELITE_TIER = {"T4": 1, "T3": 2, "T2": 3, "T1": 4}     # global T4 = KR Tier1 = 하급
TIER_BY_KO = {"하급": 1, "중급": 2, "상급": 3, "최상급": 4}
PARTS = ["Cap", "Clothes", "Pants", "Glove", "Cape", "Shoulder", "Belt", "Shoes", "Ring", "Ring2", "Pendant",
         "EarAccessory", "EyeAccessory", "BrowAccessory", "Pocket"]


def opt_row(o):
    return [o["type"], o["min"], o["max"], o["steps"], o["factorIndex"]]


def gen_equipment(d, prog):
    e = d["equipment"]
    factor_idx = set()
    pools = {}
    gear = {}
    for g in e["gear"]:
        grp = {o["groupIndex"] for o in g["subPool"]}
        assert len(grp) == 1
        gid = grp.pop()
        pool = [opt_row(o) for o in g["subPool"]]
        if gid in pools:
            assert pools[gid] == pool
        pools[gid] = pool
        lines = [g["subLineCountProbPermille"][str(i)] for i in range(5)]
        assert sum(lines) == 1000, g["code"]
        rec = {
            "part": g["part"],
            "grade": g["grade"],
            "tier": g["tier"],
            "src": g["sourceKind"],
            "main": [opt_row(o) for o in g["main"]],
            "pool": gid,
            "lines": lines,
        }
        if g["fixedSub"]:
            rec["fixed"] = [opt_row(o) for o in g["fixedSub"]]
        if g.get("nameKo"):
            rec["name"] = g["nameKo"]
        lv = g.get("dropLevel") or g.get("partyQuest")
        if lv:
            rec["dropLevel"] = [lv["min"], lv["max"]]
        if g.get("partyQuest"):
            rec["quest"] = g["partyQuest"]["quest"]
            rec["difficulty"] = g["partyQuest"]["difficulty"]
        for o in g["main"] + g["subPool"] + g["fixedSub"]:
            factor_idx.add(o["factorIndex"])
        gear[g["code"]] = rec
    assert len(gear) == 291

    table = e["levelFactors"]["table"]
    factors = {}
    for fi in sorted(factor_idx):
        factors[fi] = [table[str(lv)][fi] for lv in range(1, MAX_ITEM_LEVEL + 1)]   # 0-based column index
    assert all(v == 1000 for v in factors[8])

    conv = {}
    for r in e["subOptionConversion"]["costTable"]:
        gk = GRADE_BY_KO[r["grade"]]
        conv.setdefault(gk, {})[r["tier"]] = [[c["convertStone"], c["meso"]] for c in r["costs"]]

    es = prog["eliteSummon"]
    levels = []
    for row in sorted(es["levels"], key=lambda r: r["level"]):
        rates = []
        for label, w in row["tierRatesPer10000"].items():
            gname, t = label.rsplit(" ", 1)
            rates.append([ELITE_GRADE[gname], ELITE_TIER[t], w])
        rates.sort(key=lambda x: (GRADE_CODE[x[0]], x[1]))
        assert sum(x[2] for x in rates) == 10000, row["level"]
        levels.append({
            "cost": row["pointsPerSummon"],
            "drops": row["equipmentDropsPerKill"],
            "gauge": row["maxStoredPoints(Max_Gacha_Gauge)"],
            "lucky": row["luckySpawnCount"],
            "meso": row["levelUpMeso(Level_Up_Gold_Cost)"],
            "delay": row["levelUpDelaySec"],
            "steps": row["steps"],
            "stepCost": row["gearStonesPerStep"],
            "creature": row["creatureIndex"],
            "rates": rates,
        })
    assert len(levels) == es["currentMaxLevelKR"] == 40
    elite = {
        "maxLevel": len(levels),
        "levels": levels,
        "parts": ["Cap", "Clothes", "Pants", "Glove", "Cape", "Shoulder", "Belt", "Shoes"],
        "shoulderMinGrade": "Grade3",     # FAQ via novasmc: shoulders drop from elites only at Epic+
    }

    br = d["dropTables"]["bossRaidEquipment"]["rows"]
    raid_name = {}
    for code, g in gear.items():
        if g["src"] == "bossRaid":
            raid_name.setdefault((g["name"], g["grade"], g["tier"]), code)
    raid_rows = []
    for r in br:
        key = (r["item"], GRADE_BY_KO[r["grade"]], TIER_BY_KO[r["tier"]])
        raid_rows.append({"boss": r["boss"], "difficulty": r["difficulty"], "code": raid_name[key],
                          "permille": raw(r["percent"], 10), "burningPermille": raw(r["burningUpPercent"], 10)})
    pq = d["dropTables"]["partyQuestEquipment"]
    pq_rows = []
    for code, g in sorted(gear.items()):
        if g["src"] == "partyQuest":
            pq_rows.append({"quest": g["quest"], "difficulty": g["difficulty"], "code": code})
    drops = {
        "bossRaid": raid_rows,
        "partyQuest": pq_rows,
        "partyQuestPermille": {r["difficulty"]: [raw(r["percent"], 10), raw(r["burningUpPercent"], 10)]
                               for r in pq["dropPercentByDifficulty"]},
    }

    labels = {
        "grades": e["gradeLabels"],
        "gradeOrder": e["gradeLadder"],
        "tiers": {int(k): v for k, v in e["tierLabels"].items()},
        "parts": e["partLabels"],
        "partOrder": PARTS,
        "stats": e["statLabels"],
        "percentStats": e["percentStatTypes_valueDiv10"],
    }
    assert set(PARTS) == set(e["partLabels"])
    write(os.path.join(OUT, "Equipment.lua"), [
        ("D.EquipLabels", labels, " "),
        ("D.EquipLevelFactor", factors, None),
        ("D.EquipOptionPools", pools, None),
        ("D.Gear", gear, None),
        ("D.SubOptionConversion", conv, None),
        ("D.EliteSummon", elite, None),
        ("D.EquipDrops", drops, " "),
    ], note="""
Equipment (itemlibrary inline data, client 1.18.0) + KR elite monster summoning table (mekipick, 40 levels).
Option rows: {StatType, min, max, steps, factorIndex}; percent stats are already raw (x10).
value(step) = floor(min * EquipLevelFactor[factorIndex][itemLevel] / 1000) + floor((max - min) * step / steps),
step in 1..steps (steps == 0: constant). Gear.lines = permille for 0..4 sub lines. Gear.pool -> EquipOptionPools.
SubOptionConversion[grade][tier][attempt] = {변환석, 메소} (attempt 9 = 9th and later).
EliteSummon.levels[L]: cost = points per summon, drops = items per kill, gauge = max stored points,
steps x stepCost = 장비 강화석 to raise L -> L+1, then meso + delay seconds; rates = {grade, tier, per 10000}.""")


def main(argv):
    d = load_json(os.path.join(SPEC, "items-gacha.json"))
    prog = find_progression(argv)
    js = load_json(os.path.join(SPEC, "jobs-skills.json"))
    job_by_en = {j["nameEn"]: j["key"] for j in js["jobs"]}
    os.makedirs(OUT, exist_ok=True)
    gen_summon(d, job_by_en)
    gen_weapons(d)
    gen_companions(d, prog, job_by_en)
    gen_equipment(d, prog)
    print("ok")


if __name__ == "__main__":
    main(sys.argv)
