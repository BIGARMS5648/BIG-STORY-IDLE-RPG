"""Small helpers to emit Lua table literals from Python data."""
import re

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
    "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
}
BIGNUM = re.compile(r"^-?\d{1,40}$")


def lua_str(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif o < 32:
            out.append("\\%d" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        if abs(v) < 2 ** 53:
            return str(v)
        return repr(float(v))
    f = float(v)
    if f == int(f) and abs(f) < 2 ** 53:
        return str(int(f))
    return repr(f)


def to_lua(v, indent=None, level=0, bignum_strings=False):
    """Convert a Python value to a Lua literal.

    bignum_strings: convert digit-only strings (big integers serialized as strings
    in the spec) to Lua numbers.
    """
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return lua_num(v)
    if isinstance(v, str):
        if bignum_strings and BIGNUM.match(v):
            return lua_num(int(v))
        return lua_str(v)
    nl = "" if indent is None else "\n" + indent * (level + 1)
    end_nl = "" if indent is None else "\n" + indent * level
    if isinstance(v, (list, tuple)):
        if not v:
            return "{}"
        has_nil = any(x is None for x in v)
        parts = []
        for i, x in enumerate(v):
            if has_nil:
                if x is None:
                    continue
                parts.append("[%d]=%s" % (i + 1, to_lua(x, indent, level + 1, bignum_strings)))
            else:
                parts.append(to_lua(x, indent, level + 1, bignum_strings))
        return "{" + nl + ("," + nl).join(parts) + end_nl + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        parts = []
        for k, x in v.items():
            if x is None:
                continue
            if isinstance(k, (int, float)) and not isinstance(k, bool):
                key = "[%s]" % lua_num(k)
            elif isinstance(k, str) and re.match(r"^-?\d+$", k) and len(k) < 16:
                key = "[%s]" % k
            elif isinstance(k, str) and IDENT.match(k) and k not in LUA_KEYWORDS:
                key = k
            else:
                key = "[%s]" % lua_str(str(k))
            parts.append("%s=%s" % (key, to_lua(x, indent, level + 1, bignum_strings)))
        return "{" + nl + ("," + nl).join(parts) + end_nl + "}"
    raise TypeError("cannot convert %r" % type(v))


HEADER = "-- GENERATED by tools/gen_data.py from research/spec. Do not edit by hand.\n" \
         "local ADDON, ns = ...\nns.Data = ns.Data or {}\nlocal D = ns.Data\n"


def write_lua(path, assignments, note=None):
    """assignments: list of (lua_lhs, python_value, opts)"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER)
        if note:
            for line in note.splitlines():
                f.write("-- " + line + "\n")
        for lhs, value, opts in assignments:
            opts = opts or {}
            f.write("%s = %s\n" % (lhs, to_lua(value, opts.get("indent"), 0, opts.get("bignum", False))))
